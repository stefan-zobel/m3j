"""Generate src/main/java/m3j/fingerprint/PolyBasis.java from CM3's PolyBasis.i3.

Usage: python3 tools/gen_polybasis.py CM3_SRC [OUT]

CM3_SRC is the root of a CM3 source tree; the tables are read from
m3-libs/m3core/src/fingerprint/PolyBasis.i3. OUT defaults to the Java file
in this repository. The tables are copied value by value, in their original
order, so that the Java port uses exactly the numbers of the original.
"""

import re
import sys
from pathlib import Path

TABLES = ["poly64", "poly72", "poly80", "poly88",
          "power", "power8", "power16", "power24"]


def parse(text):
    p = re.search(r"P\s*=\s*X\s*\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}", text)
    if not p:
        sys.exit("PolyBasis.i3: constant P not found")
    tables = {}
    for name in TABLES:
        m = re.search(r"\b" + name + r"\s*=\s*T\s*\{\s*\(\*(.*?)\*\)(.*?)\}\s*;",
                      text, re.S)
        if not m:
            sys.exit(f"PolyBasis.i3: table {name} not found")
        comment = " ".join(m.group(1).split())
        pairs = re.findall(r"X\s*\{\s*(-?\d+|MIN_INT)\s*,\s*(-?\d+|MIN_INT)\s*\}",
                           m.group(2))
        if len(pairs) != 256:
            sys.exit(f"PolyBasis.i3: table {name} has {len(pairs)} entries, not 256")
        for a, b in pairs:
            for v in (-2**31 if x == "MIN_INT" else int(x) for x in (a, b)):
                if not -2**31 <= v < 2**31:
                    sys.exit(f"PolyBasis.i3: value {v} in {name} is not an Int32")
        tables[name] = (comment, pairs)
    return (p.group(1), p.group(2)), tables


def emit(p, tables):
    out = []
    w = out.append
    w("// Java port of CM3's m3-libs/m3core/src/fingerprint/PolyBasis.i3.")
    w("// Original: Copyright (C) 1989, 1990, Digital Equipment Corporation.")
    w("// Distributed under the Digital license in licenses/COPYRIGHT-DEC.")
    w("//")
    w("// Generated by tools/gen_polybasis.py from PolyBasis.i3; do not edit.")
    w("")
    w("package m3j.fingerprint;")
    w("")
    w("/**")
    w(" * A single polynomial P and associated tables for arithmetic MOD P.")
    w(" *")
    w(" * <p>An element {@code X} is a {@link Poly} value, an {@code int[2]};")
    w(" * a table {@code T} is an {@code int[256][2]}. The tables must not be")
    w(" * modified.")
    w(" */")
    w("final class PolyBasis {")
    w("    private PolyBasis() {}")
    w("")
    w(f"    /** An irreducible degree 61 polynomial * X^3. */")
    w(f"    static final int[] P = {{ {p[0]}, {p[1]} }};")
    w("")
    w("    static final int MIN_INT = Integer.MIN_VALUE;")
    for name in TABLES:
        comment, pairs = tables[name]
        w("")
        w(f"    /** {comment} */")
        w(f"    static final int[][] {name} = {{")
        row = []
        for i, (a, b) in enumerate(pairs):
            row.append(f"{{ {a}, {b} }}")
            if len(row) == 3 or i == len(pairs) - 1:
                w("        " + ", ".join(row) + ("," if i < len(pairs) - 1 else ""))
                row = []
        w("    };")
    w("}")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    src = Path(sys.argv[1]) / "m3-libs/m3core/src/fingerprint/PolyBasis.i3"
    here = Path(__file__).resolve().parent.parent
    dst = Path(sys.argv[2]) if len(sys.argv) == 3 else \
        here / "src/main/java/m3j/fingerprint/PolyBasis.java"
    p, tables = parse(src.read_text(encoding="latin-1"))
    dst.write_text(emit(p, tables), encoding="utf-8", newline="\n")
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
